#if PLATFORM_WINDOWS

namespace SpoutUE
{
	DXGI_FORMAT ToPublishFormat(EPixelFormat Format)
	{
		switch (Format)
		{
		case PF_B8G8R8A8:			return DXGI_FORMAT_B8G8R8A8_UNORM;
		case PF_R8G8B8A8:			return DXGI_FORMAT_R8G8B8A8_UNORM;
		case PF_A8R8G8B8:			return DXGI_FORMAT_B8G8R8A8_UNORM;
		case PF_A2B10G10R10:		return DXGI_FORMAT_R10G10B10A2_UNORM;
		case PF_FloatRGBA:			return DXGI_FORMAT_R16G16B16A16_FLOAT;
		case PF_A16B16G16R16:		return DXGI_FORMAT_R16G16B16A16_UNORM;
		case PF_A32B32G32R32F:		return DXGI_FORMAT_R32G32B32A32_FLOAT;
		case PF_FloatR11G11B10:		return DXGI_FORMAT_R11G11B10_FLOAT;
		default:					return DXGI_FORMAT_UNKNOWN;
		}
	}

	EPixelFormat FromDXGIFormat(DXGI_FORMAT Format)
	{
		switch (Format)
		{
		case DXGI_FORMAT_B8G8R8A8_UNORM:
		case DXGI_FORMAT_B8G8R8A8_UNORM_SRGB:
		case DXGI_FORMAT_B8G8R8A8_TYPELESS:
		case DXGI_FORMAT_B8G8R8X8_UNORM:
			return PF_B8G8R8A8;

		case DXGI_FORMAT_R8G8B8A8_UNORM:
		case DXGI_FORMAT_R8G8B8A8_UNORM_SRGB:
		case DXGI_FORMAT_R8G8B8A8_TYPELESS:
			return PF_R8G8B8A8;

		case DXGI_FORMAT_R10G10B10A2_UNORM:
		case DXGI_FORMAT_R10G10B10A2_TYPELESS:
			return PF_A2B10G10R10;

		case DXGI_FORMAT_R16G16B16A16_FLOAT:
			return PF_FloatRGBA;

		case DXGI_FORMAT_R16G16B16A16_UNORM:
			return PF_A16B16G16R16;

		case DXGI_FORMAT_R32G32B32A32_FLOAT:
			return PF_A32B32G32R32F;

		case DXGI_FORMAT_R11G11B10_FLOAT:
			return PF_FloatR11G11B10;

		default:
			return PF_Unknown;
		}
	}

	FString DXGIFormatToString(DXGI_FORMAT Format)
	{
		switch (Format)
		{
		case DXGI_FORMAT_UNKNOWN:					return TEXT("UNKNOWN");
		case DXGI_FORMAT_B8G8R8A8_UNORM:			return TEXT("B8G8R8A8_UNORM");
		case DXGI_FORMAT_B8G8R8A8_UNORM_SRGB:		return TEXT("B8G8R8A8_UNORM_SRGB");
		case DXGI_FORMAT_B8G8R8A8_TYPELESS:			return TEXT("B8G8R8A8_TYPELESS");
		case DXGI_FORMAT_B8G8R8X8_UNORM:			return TEXT("B8G8R8X8_UNORM");
		case DXGI_FORMAT_R8G8B8A8_UNORM:			return TEXT("R8G8B8A8_UNORM");
		case DXGI_FORMAT_R8G8B8A8_UNORM_SRGB:		return TEXT("R8G8B8A8_UNORM_SRGB");
		case DXGI_FORMAT_R8G8B8A8_TYPELESS:			return TEXT("R8G8B8A8_TYPELESS");
		case DXGI_FORMAT_R10G10B10A2_UNORM:			return TEXT("R10G10B10A2_UNORM");
		case DXGI_FORMAT_R16G16B16A16_FLOAT:		return TEXT("R16G16B16A16_FLOAT");
		case DXGI_FORMAT_R16G16B16A16_UNORM:		return TEXT("R16G16B16A16_UNORM");
		case DXGI_FORMAT_R32G32B32A32_FLOAT:		return TEXT("R32G32B32A32_FLOAT");
		case DXGI_FORMAT_R11G11B10_FLOAT:			return TEXT("R11G11B10_FLOAT");
		default:									return FString::Printf(TEXT("DXGI(%d)"), static_cast<int32>(Format));
		}
	}
}

#endif // PLATFORM_WINDOWS
